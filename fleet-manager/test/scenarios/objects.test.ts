import { describe, expect, it } from "vitest";
import {
  type KubeObject,
  alignObservedGeneration,
  createOrder,
  diffStates,
  objectKey,
  parseObjects,
  replaceUIDs,
} from "./objects";

function object(
  kind: string,
  name: string,
  extra: Partial<KubeObject["metadata"]> = {},
  apiVersion = "v1",
): KubeObject {
  return {
    apiVersion,
    kind,
    metadata: { name, namespace: "team-a", uid: `uid-${name}`, ...extra },
  };
}

const owned = (owner: string) => ({
  ownerReferences: [{ uid: `uid-${owner}` }],
});

const names = (objs: readonly KubeObject[]) => objs.map((o) => o.metadata.name);

describe("parseObjects", () => {
  it("reads the documents of a generated file and skips the header", () => {
    const objs = parseObjects(
      "# Generated by make fleet-scenarios.\n---\napiVersion: v1\nkind: Namespace\nmetadata:\n  name: a\n---\n",
    );
    expect(objs).toEqual([
      { apiVersion: "v1", kind: "Namespace", metadata: { name: "a" } },
    ]);
  });
});

describe("objectKey", () => {
  it("tells apart a namespaced and a cluster-scoped object of the same name", () => {
    const ns = object("ConfigMap", "a");
    const cluster = { ...ns, metadata: { name: "a" } };
    expect(objectKey(ns)).not.toBe(objectKey(cluster));
  });
});

describe("createOrder", () => {
  it("puts namespaces first, owners before dependents, and Events last", () => {
    const event = object("Event", "e", {}, "events.k8s.io/v1");
    const pod = object("Pod", "pod", owned("rs"));
    const rs = object("ReplicaSet", "rs", owned("deploy"), "apps/v1");
    const deploy = object("Deployment", "deploy", {}, "apps/v1");
    const ns = {
      apiVersion: "v1",
      kind: "Namespace",
      metadata: { name: "ns" },
    };

    expect(names(createOrder([event, pod, rs, deploy, ns]))).toEqual([
      "ns",
      "deploy",
      "rs",
      "pod",
      "e",
    ]);
  });

  it("keeps the input order of objects that do not depend on each other", () => {
    const a = object("ConfigMap", "a");
    const b = object("ConfigMap", "b");
    const c = object("ConfigMap", "c");
    expect(names(createOrder([c, a, b]))).toEqual(["c", "a", "b"]);
  });

  it("does not hold back an object whose owner is not in the scenario", () => {
    const a = object("ConfigMap", "a", owned("missing"));
    const b = object("ConfigMap", "b");
    expect(names(createOrder([a, b]))).toEqual(["a", "b"]);
  });

  it("throws on an owner cycle and names both objects", () => {
    const a = object("ConfigMap", "a", owned("b"));
    const b = object("ConfigMap", "b", owned("a"));
    expect(() => createOrder([a, b])).toThrow(
      /ConfigMap team-a\/a.*ConfigMap team-a\/b/,
    );
  });

  it("does not change its input", () => {
    const input = [
      object("ConfigMap", "a", owned("b")),
      object("ConfigMap", "b"),
    ];
    createOrder(input);
    expect(names(input)).toEqual(["a", "b"]);
  });
});

describe("replaceUIDs", () => {
  it("replaces a scenario UID in an owner reference, a label, an annotation, a managedFields key, a field manager name, and an Event regarding and related", () => {
    const obj = {
      apiVersion: "events.k8s.io/v1",
      kind: "Event",
      metadata: {
        name: "e",
        ownerReferences: [{ uid: "S1" }],
        labels: { "camunda.io/owner-uid": "S1" },
        annotations: { "camunda.io/storage-claim-holder-uid": "S1" },
        managedFields: [
          {
            manager: "camundacluster-S1",
            fieldsV1: { "f:metadata": { 'k:{"uid":"S1"}': {} } },
          },
        ],
      },
      regarding: { uid: "S1" },
      related: { uid: "S1" },
    };
    const before = JSON.stringify(obj);

    const result = replaceUIDs(obj, new Map([["S1", "R1"]]));

    const text = JSON.stringify(result);
    expect(text).not.toContain("S1");
    expect(text.match(/R1/g)).toHaveLength(7);
    expect(JSON.stringify(obj)).toBe(before);
  });
});

describe("alignObservedGeneration", () => {
  it("moves an observed generation that equals the recorded one, at any depth", () => {
    const status = {
      observedGeneration: 1,
      conditions: [{ observedGeneration: 1 }, { observedGeneration: 0 }],
    };
    expect(alignObservedGeneration(status, 1, 3)).toEqual({
      observedGeneration: 3,
      conditions: [{ observedGeneration: 3 }, { observedGeneration: 0 }],
    });
  });

  it("does not change its input", () => {
    const status = { observedGeneration: 1 };
    alignObservedGeneration(status, 1, 3);
    expect(status).toEqual({ observedGeneration: 1 });
  });
});

describe("diffStates", () => {
  it("creates, updates, and removes by key", () => {
    const a = object("ConfigMap", "a");
    const b = object("ConfigMap", "b");
    const changedB = { ...b, data: { x: "1" } };
    const c = object("ConfigMap", "c");
    const d = object("ConfigMap", "d");

    const diff = diffStates([a, b, c], [a, changedB, d]);

    expect(diff.create).toEqual([d]);
    expect(diff.update).toEqual([changedB]);
    expect(diff.remove).toEqual([c]);
  });

  it("creates owners first and removes dependents first", () => {
    const owner = object("Deployment", "owner", {}, "apps/v1");
    const dependent = object("ReplicaSet", "dep", owned("owner"), "apps/v1");

    expect(names(diffStates([], [dependent, owner]).create)).toEqual([
      "owner",
      "dep",
    ]);
    expect(names(diffStates([owner, dependent], []).remove)).toEqual([
      "dep",
      "owner",
    ]);
  });
});
