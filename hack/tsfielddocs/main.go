// Command tsfielddocs writes the field docs of the fleet manager: for each
// kind and field path, the description of the CRD schema and the anchor of
// the Go type that holds the field in docs/crds/api-reference.md. The
// FieldHelp component shows them next to a form label.
//
// It reads each CRD in the crds directory and takes the Go type of its kind
// from the scheme of internal/manager. A field path joins the JSON names from
// the root with dots, and an array adds no segment. The walk skips
// apiVersion, kind, and metadata, and does not go into a map value. It stops
// at a field whose type is not a struct of the api module, because the API
// reference has no anchor for its sub-fields. The anchor is a # and the type
// name in lower case, as crd-ref-docs writes it. A field of an inline
// embedded struct belongs to the struct that embeds it, as in the reference.
//
// Usage: tsfielddocs -crds <dir> -out <file>
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"strings"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/apimachinery/pkg/runtime/schema"
	"sigs.k8s.io/yaml"

	"github.com/konsole-is/camunda-operator/internal/manager"
)

// fieldDoc is the help of one field path.
type fieldDoc struct {
	Description string `json:"description"`
	Anchor      string `json:"anchor"`
}

// apiModule is the module of the types that the API reference documents.
const apiModule = "github.com/konsole-is/camunda-operator/api"

const header = `// Code generated by hack/tsfielddocs from config/crd/bases and the api types. DO NOT EDIT.
// Run make fleet-generate to update it.

/** FieldDoc is the CRD description of a field and the anchor of its type in the API reference. */
export interface FieldDoc {
  description: string;
  anchor: string;
}

/**
 * FieldDocs holds a FieldDoc by API group, kind, and field path. A path joins
 * the JSON names with dots. An array adds no segment. A group, kind, or path
 * that names a property of Object.prototype, such as constructor, gives that
 * property, not undefined.
 */
export type FieldDocs = Partial<Record<string, Partial<Record<string, Partial<Record<string, FieldDoc>>>>>>;

export const fieldDocs: FieldDocs = `

func main() {
	crds := flag.String("crds", "config/crd/bases", "the directory of the CRDs")
	out := flag.String("out", "fleet-manager/src/generated/fielddocs.ts", "the file to write")
	flag.Parse()

	scheme := runtime.NewScheme()
	if err := manager.AddToScheme(scheme); err != nil {
		fmt.Fprintf(os.Stderr, "building the scheme of the manager: %v\n", err)
		os.Exit(1)
	}

	docs, err := build(*crds, scheme)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	raw, err := render(docs)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	if err := os.WriteFile(*out, raw, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "writing the field docs: %v\n", err)
		os.Exit(1)
	}
}

// build returns the field docs of every CRD in dir, by group, kind, and
// field path. Each kind must have a Go type in scheme.
func build(dir string, scheme *runtime.Scheme) (map[string]map[string]map[string]fieldDoc, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil {
		return nil, fmt.Errorf("listing the CRDs: %w", err)
	}

	docs := map[string]map[string]map[string]fieldDoc{}
	for _, path := range paths {
		group, kind, kindDocs, err := buildCRD(path, scheme)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}

		if docs[group] == nil {
			docs[group] = map[string]map[string]fieldDoc{}
		}
		docs[group][kind] = kindDocs
	}

	return docs, nil
}

// buildCRD returns the group, the kind, and the field docs of the CRD in path.
func buildCRD(path string, scheme *runtime.Scheme) (string, string, map[string]fieldDoc, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", "", nil, err
	}

	var crd apiextensionsv1.CustomResourceDefinition
	if err := yaml.Unmarshal(raw, &crd); err != nil {
		return "", "", nil, fmt.Errorf("parsing the CRD: %w", err)
	}

	served := slices.DeleteFunc(
		slices.Clone(crd.Spec.Versions),
		func(v apiextensionsv1.CustomResourceDefinitionVersion) bool { return !v.Served },
	)
	if len(served) != 1 {
		return "", "", nil, fmt.Errorf(
			"%s serves %d versions, and the generated names hold no version",
			crd.Name,
			len(served),
		)
	}

	version := served[0]
	if version.Schema == nil || version.Schema.OpenAPIV3Schema == nil {
		return "", "", nil, fmt.Errorf("version %s of %s has no schema", version.Name, crd.Name)
	}

	gvk := schema.GroupVersionKind{Group: crd.Spec.Group, Version: version.Name, Kind: crd.Spec.Names.Kind}
	obj, err := scheme.New(gvk)
	if err != nil {
		return "", "", nil, fmt.Errorf("the scheme of internal/manager has no Go type for %s: %w", gvk, err)
	}

	docs, err := walk(reflect.TypeOf(obj).Elem(), version.Schema.OpenAPIV3Schema, apiModule)
	if err != nil {
		return "", "", nil, fmt.Errorf("%s: %w", gvk.Kind, err)
	}

	return crd.Spec.Group, crd.Spec.Names.Kind, docs, nil
}

// walk returns the docs of every field path of the kind root that s
// describes. local is the package path prefix of the types that the API
// reference documents.
func walk(root reflect.Type, s *apiextensionsv1.JSONSchemaProps, local string) (map[string]fieldDoc, error) {
	props := maps.Clone(s.Properties)
	for _, name := range []string{"apiVersion", "kind", "metadata"} {
		delete(props, name)
	}

	docs := map[string]fieldDoc{}
	if err := walkStruct(docs, "", root, props, local); err != nil {
		return nil, err
	}

	return docs, nil
}

// walkStruct adds to docs the properties of struct t under prefix, and the
// properties of each field whose type is a struct under local.
func walkStruct(
	docs map[string]fieldDoc,
	prefix string,
	t reflect.Type,
	props map[string]apiextensionsv1.JSONSchemaProps,
	local string,
) error {
	fields := jsonFields(t)
	anchor := "#" + strings.ToLower(t.Name())
	for _, name := range slices.Sorted(maps.Keys(props)) {
		path := name
		if prefix != "" {
			path = prefix + "." + name
		}

		fieldType, ok := fields[name]
		if !ok {
			return fmt.Errorf("%s is in the CRD schema and not in the Go type %s", path, t.Name())
		}

		prop := props[name]
		docs[path] = fieldDoc{Description: prop.Description, Anchor: anchor}

		next := elem(fieldType)
		if next.Kind() != reflect.Struct || !inModule(next.PkgPath(), local) {
			continue
		}

		if prop.Items != nil && prop.Items.Schema != nil {
			prop = *prop.Items.Schema
		}
		if err := walkStruct(docs, path, next, prop.Properties, local); err != nil {
			return err
		}
	}

	return nil
}

// jsonFields returns the type of each field of struct t by its JSON name. The
// fields of an embedded struct without a JSON name are in place, as
// encoding/json reads them.
func jsonFields(t reflect.Type) map[string]reflect.Type {
	fields := map[string]reflect.Type{}
	for f := range t.Fields() {
		name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
		switch {
		case name == "-":
		case name == "" && f.Anonymous:
			maps.Copy(fields, jsonFields(elem(f.Type)))
		case !f.IsExported():
		case name == "":
			fields[f.Name] = f.Type
		default:
			fields[name] = f.Type
		}
	}

	return fields
}

// elem returns t without its pointers, slices, and arrays.
func elem(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Array {
		t = t.Elem()
	}

	return t
}

// inModule reports whether pkg is the package path local or a package under it.
func inModule(pkg, local string) bool {
	return pkg == local || strings.HasPrefix(pkg, local+"/")
}

// render returns fielddocs.ts for docs. encoding/json sorts the keys, so the
// output is the same for the same input.
func render(docs map[string]map[string]map[string]fieldDoc) ([]byte, error) {
	var body bytes.Buffer
	enc := json.NewEncoder(&body)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(docs); err != nil {
		return nil, fmt.Errorf("encoding the field docs: %w", err)
	}

	return slices.Concat([]byte(header), bytes.TrimRight(body.Bytes(), "\n"), []byte(";\n")), nil
}
