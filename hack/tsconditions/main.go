// Command tsconditions writes the condition types of the api groups to
// TypeScript. The fleet manager types the condition placement map of a kind
// on its set, so a new condition type fails the app build until the map
// places it.
//
// It reads every non-test .go file of each group package under the api
// directory. A group package is a directory that holds groupversion_info.go.
// A constant whose name starts with Condition is a condition type. A
// constant of conditions.go is in the set of every kind of the group. A
// constant of another file is in the set of the one kind that the file
// declares. A file that declares a condition type and no kind, or more than
// one kind, fails the run. The set of every kind also holds Ready of api/v1,
// which every kind reports, also in a group that does not declare it.
//
// Usage: tsconditions -api <dir> -out <file>
package main

import (
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	v1 "github.com/konsole-is/camunda-operator/api/v1"
)

// group is the condition vocabulary of one API group.
type group struct {
	// Name is the API group, for example core.camunda.io.
	Name string
	// Prefix is the first label of Name. It starts every generated name.
	Prefix string
	// Shared holds the types of conditions.go.
	Shared []string
	// Kinds holds the own types of each kind of the group. A kind without
	// own types has a nil entry.
	Kinds map[string][]string
}

const (
	rootMarker = "+kubebuilder:object:root=true"
	header     = `// Code generated by hack/tsconditions from the api packages. DO NOT EDIT.
// Run make fleet-generate to update it.
//
// For each kind, the condition types that it can report: Ready, the shared
// types of its group, and its own types.
`
)

var (
	conditionName = regexp.MustCompile(`^Condition[A-Z]`)
	groupMarker   = regexp.MustCompile(`\+groupName=(\S+)`)
	groupPrefix   = regexp.MustCompile(`^[a-z][a-z0-9]*$`)
)

func main() {
	apiDir := flag.String("api", "api", "the directory of the api module")
	out := flag.String("out", "fleet-manager/src/generated/conditions.ts", "the file to write")
	flag.Parse()

	raw, err := generate(*apiDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	if err := os.WriteFile(*out, raw, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "writing the condition types: %v\n", err)
		os.Exit(1)
	}
}

// generate returns conditions.ts for the group packages under apiDir.
func generate(apiDir string) ([]byte, error) {
	groups, err := readGroups(apiDir)
	if err != nil {
		return nil, err
	}

	return render(groups), nil
}

// readGroups returns the vocabulary of every group package under apiDir,
// sorted by group name.
func readGroups(apiDir string) ([]group, error) {
	var groups []group
	err := filepath.WalkDir(apiDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || d.Name() != "groupversion_info.go" {
			return err
		}

		g, err := readGroup(filepath.Dir(path))
		if err != nil {
			return err
		}

		groups = append(groups, g)
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("reading the api groups under %s: %w", apiDir, err)
	}

	if len(groups) == 0 {
		return nil, fmt.Errorf("no group package under %s", apiDir)
	}

	seen := map[string]string{}
	for _, g := range groups {
		if other, ok := seen[g.Prefix]; ok {
			return nil, fmt.Errorf(
				"the groups %s and %s both start with %q, so their generated names collide",
				other,
				g.Name,
				g.Prefix,
			)
		}
		seen[g.Prefix] = g.Name
	}

	slices.SortFunc(groups, func(a, b group) int { return strings.Compare(a.Name, b.Name) })
	return groups, nil
}

// readGroup reads the condition types of the group package in dir.
func readGroup(dir string) (group, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return group{}, fmt.Errorf("listing the files of %s: %w", dir, err)
	}

	g := group{Kinds: map[string][]string{}}
	fset := token.NewFileSet()
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}

		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return group{}, fmt.Errorf("parsing %s: %w", path, err)
		}

		if m := groupMarker.FindStringSubmatch(file.Doc.Text()); m != nil {
			g.Name = m[1]
		}

		kinds := rootKinds(file)
		for _, kind := range kinds {
			if _, ok := g.Kinds[kind]; !ok {
				g.Kinds[kind] = nil
			}
		}

		types, err := conditionTypes(fset, file)
		if err != nil {
			return group{}, err
		}

		switch {
		case len(types) == 0:
		case filepath.Base(path) == "conditions.go":
			g.Shared = append(g.Shared, types...)
		case len(kinds) == 1:
			g.Kinds[kinds[0]] = append(g.Kinds[kinds[0]], types...)
		default:
			return group{}, fmt.Errorf(
				"%s declares condition types and %d kinds: declare them in conditions.go, "+
					"or in the types file of the one kind that reports them",
				path,
				len(kinds),
			)
		}
	}

	if g.Name == "" {
		return group{}, fmt.Errorf("%s has no +groupName marker", dir)
	}

	g.Prefix, _, _ = strings.Cut(g.Name, ".")
	if !groupPrefix.MatchString(g.Prefix) {
		return group{}, fmt.Errorf("the group %s does not start with a lower-case word", g.Name)
	}

	return g, nil
}

// rootKinds returns the kinds that file declares: the types with the root
// object marker, without the list type of each kind.
func rootKinds(file *ast.File) []string {
	var roots []string
	prevEnd := file.Name.End()
	for _, decl := range file.Decls {
		start := prevEnd
		prevEnd = decl.End()
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE || !hasRootMarker(file, start, gen.Pos()) {
			continue
		}

		for _, spec := range gen.Specs {
			roots = append(roots, spec.(*ast.TypeSpec).Name.Name)
		}
	}

	return slices.DeleteFunc(slices.Clone(roots), func(name string) bool {
		kind, isList := strings.CutSuffix(name, "List")
		return isList && slices.Contains(roots, kind)
	})
}

// hasRootMarker reports whether a comment between from and to holds the root
// object marker.
func hasRootMarker(file *ast.File, from, to token.Pos) bool {
	// The marker is often its own comment group, set off from the doc
	// comment by a blank line, so the Doc of the declaration does not hold it.
	return slices.ContainsFunc(file.Comments, func(cg *ast.CommentGroup) bool {
		return cg.Pos() > from && cg.End() < to && strings.Contains(cg.Text(), rootMarker)
	})
}

// conditionTypes returns the values of the Condition constants of file.
func conditionTypes(fset *token.FileSet, file *ast.File) ([]string, error) {
	var types []string
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}

		for _, spec := range gen.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, name := range vs.Names {
				if !conditionName.MatchString(name.Name) {
					continue
				}

				value, err := stringValue(vs, i)
				if err != nil {
					return nil, fmt.Errorf("%s: %s: %w", fset.Position(name.Pos()), name.Name, err)
				}

				types = append(types, value)
			}
		}
	}

	return types, nil
}

// stringValue returns the value of the i-th name of vs, which must be a
// string literal.
func stringValue(vs *ast.ValueSpec, i int) (string, error) {
	if i >= len(vs.Values) {
		return "", errors.New("a condition type must have its own string literal value")
	}

	lit, ok := vs.Values[i].(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return "", errors.New("a condition type must be a string literal")
	}

	return strconv.Unquote(lit.Value)
}

// render writes the shared set of each group and the set of each kind.
func render(groups []group) []byte {
	var b strings.Builder
	b.WriteString(header)
	for _, g := range groups {
		writeSet(&b, g.Prefix+"Shared", g.Shared)
		for _, kind := range slices.Sorted(maps.Keys(g.Kinds)) {
			writeSet(&b, g.Prefix+kind, slices.Concat([]string{v1.ConditionReady}, g.Shared, g.Kinds[kind]))
		}
	}

	return []byte(b.String())
}

// writeSet writes types, sorted and without duplicates, as a const array and
// its union type.
func writeSet(b *strings.Builder, name string, types []string) {
	types = slices.Compact(slices.Sorted(slices.Values(types)))
	fmt.Fprintf(b, "\nexport const %sConditionTypes = [\n", name)
	for _, t := range types {
		fmt.Fprintf(b, "  %q,\n", t)
	}

	fmt.Fprintf(
		b,
		"] as const;\nexport type %sConditionType = (typeof %sConditionTypes)[number];\n",
		strings.ToUpper(name[:1])+name[1:],
		name,
	)
}
