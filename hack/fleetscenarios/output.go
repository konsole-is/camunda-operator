package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"sigs.k8s.io/yaml"
)

// generatedHeader is the first line of each output file. writeOutputs
// removes only a file that opens with it.
const generatedHeader = "# Generated by make fleet-scenarios from scenario.yaml. Do not edit."

// encode returns objs as one YAML stream that opens with generatedHeader.
// The bytes depend only on the content of objs.
func encode(objs []unstructured.Unstructured) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(generatedHeader + "\n")
	for i := range objs {
		doc, err := yaml.Marshal(objs[i].Object)
		if err != nil {
			return nil, fmt.Errorf("encoding %s: %w", describe(&objs[i]), err)
		}
		b.WriteString("---\n")
		b.Write(doc)
	}
	return b.Bytes(), nil
}

// writeOutputs writes each file of outputs to dir, and removes each other
// .yaml file of dir that opens with generatedHeader. A file that does not
// open with it, such as scenario.yaml, is never removed. It writes nothing
// when one file of outputs cannot be encoded.
func writeOutputs(dir string, outputs map[string][]unstructured.Unstructured) error {
	encoded := map[string][]byte{}
	for name, objs := range outputs {
		data, err := encode(objs)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		encoded[name] = data
	}

	existing, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil {
		return err
	}
	for _, path := range existing {
		if _, ok := encoded[filepath.Base(path)]; ok {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(data, []byte(generatedHeader+"\n")) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}

	for name, data := range encoded {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			return err
		}
	}

	return nil
}
