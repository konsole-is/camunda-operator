// A Docker Hub pull first gets a token from auth.docker.io, and a reset of
// that request fails every spec. Google's mirror of Docker Hub needs no token.
// It is the image that both Jobs render for server version 17.
const postgresImage = "mirror.gcr.io/library/postgres:17"

// The roles of the target database, as the Database controller sets them up
// through pkg/pgbootstrap: the dump connects as the backup role, and the
// restore connects as the application role that owns the database.
const (
	targetDatabase    = "camunda"
	applicationRole   = "camunda_app"
	applicationSecret = "app-credentials"
	backupRole        = "camunda_backup"
	backupSecret      = "backup-credentials"
	rolePassword      = "role-secret"
)

// olderSchema is the schema that the dump holds. It has the shape of a
// Liquibase-managed schema: a changelog table that lists the changesets that
// ran, and a table with an index and a sequence.
const olderSchema = `
CREATE TABLE databasechangelog (
	id VARCHAR(255) NOT NULL,
	filename VARCHAR(255) NOT NULL,
	orderexecuted INT NOT NULL
);
CREATE TABLE process_instance (process_instance_key BIGINT PRIMARY KEY, state VARCHAR(20));
CREATE INDEX idx_process_instance_state ON process_instance (state);
CREATE SEQUENCE process_instance_seq;
INSERT INTO process_instance VALUES (1, 'ACTIVE');
INSERT INTO databasechangelog VALUES ('create_process_instance_table', '8.9.0.xml', 1);
`

// olderChangesets are the changelog rows of olderSchema.
var olderChangesets = []string{"create_process_instance_table"}

// newerSchema is what a newer Camunda minor adds after the dump: a table with
// an index and an identity column, a table with a foreign key into a table of
// the dump, a sequence, and views over them. It also changes a table and the
// changelog of the dump.
const newerSchema = `
ALTER TABLE process_instance ADD COLUMN suspended_date TIMESTAMP;
CREATE INDEX idx_process_instance_suspended_date ON process_instance (suspended_date);
UPDATE process_instance SET state = 'COMPLETED';
CREATE TABLE deployed_resource (
	resource_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	resource_id VARCHAR(255)
);
CREATE INDEX idx_deployed_resource_id ON deployed_resource (resource_id);
INSERT INTO deployed_resource (resource_id) VALUES ('written after the backup');
CREATE TABLE process_instance_metadata (
	process_instance_key BIGINT PRIMARY KEY REFERENCES process_instance ON DELETE CASCADE,
	metadata_id BIGSERIAL
);
INSERT INTO process_instance_metadata (process_instance_key) VALUES (1);
CREATE SEQUENCE deployed_resource_seq;
CREATE VIEW active_process_instance AS SELECT * FROM process_instance WHERE state = 'ACTIVE';
CREATE MATERIALIZED VIEW deployed_resource_count AS SELECT count(*) FROM deployed_resource;
INSERT INTO databasechangelog VALUES ('create_deployed_resource_table', '8.10.0.xml', 2);
`

func TestRestoreRebuildsTheObjectsOfTheDump(t *testing.T) {
	t.Parallel()

	target := startTarget(t)
	target.exec(t, olderSchema)
	dumped := target.objects(t)
	target.dump(t)

	target.exec(t, `
ALTER TABLE process_instance ADD COLUMN suspended_date TIMESTAMP;
CREATE INDEX idx_process_instance_suspended_date ON process_instance (suspended_date);
UPDATE process_instance SET state = 'COMPLETED';
INSERT INTO databasechangelog VALUES ('add_process_instance_suspended_date_column', '8.10.0.xml', 2);
`)
	code, output := target.restore(t)

	require.Zero(t, code, output)
	assert.Equal(t, dumped, target.objects(t))
	assert.Equal(t, olderChangesets, target.changesets(t))
	assert.Equal(t, "ACTIVE", target.queryString(t, "SELECT state FROM process_instance"))
}

// TestRestoreLeavesOnlyTheObjectsOfTheDump covers a dump of an older Camunda
// minor. Camunda 8.10 has the foreign key case: CLUSTER_VARIABLE_METADATA
// references CLUSTER_VARIABLE of 8.9.
func TestRestoreLeavesOnlyTheObjectsOfTheDump(t *testing.T) {
	t.Parallel()

	target := startTarget(t)
	target.exec(t, olderSchema)
	dumped := target.objects(t)
	target.dump(t)

	target.exec(t, newerSchema)
	code, output := target.restore(t)

	require.Zero(t, code, output)
	assert.Equal(t, dumped, target.objects(t))
	assert.Equal(t, olderChangesets, target.changesets(t))
	assert.Equal(t, "ACTIVE", target.queryString(t, "SELECT state FROM process_instance"))
}

// TestRestoreDropsOnlyTheRelationsOfTheApplicationRole pins the bounds of the
// drop: a relation of the application role goes in every schema, a table of
// another role and the members of an extension stay, also a member that the
// application role owns, and a view of another role over a dropped table goes
// with that table.
func TestRestoreDropsOnlyTheRelationsOfTheApplicationRole(t *testing.T) {
	t.Parallel()

	target := startTarget(t)
	target.exec(t, olderSchema)
	target.dump(t)

	target.exec(t, `
CREATE SCHEMA extra;
CREATE TABLE extra.wait_state (wait_state_key BIGINT PRIMARY KEY);
CREATE TABLE extension_member (id BIGINT);
`)
	backupConn := target.connect(t, backupRole)
	_, err := backupConn.Exec(t.Context(), `
CREATE TABLE table_of_another_role (id BIGINT);
CREATE VIEW view_of_another_role AS SELECT * FROM process_instance;
`)
	require.NoError(t, err)
	admin, err := pgbootstrap.Open(t.Context(), target.server, targetDatabase)
	require.NoError(t, err)
	t.Cleanup(func() { _ = admin.Close(context.Background()) })
	_, err = admin.Exec(t.Context(), `
CREATE EXTENSION pg_stat_statements;
ALTER EXTENSION pg_stat_statements ADD TABLE extension_member;
`)
	require.NoError(t, err)

	code, output := target.restore(t)
	require.Zero(t, code, output)

	relations := target.queryString(t, `
SELECT string_agg(n.nspname || '.' || c.relname, ',' ORDER BY n.nspname, c.relname)
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relname IN (
	'wait_state', 'table_of_another_role', 'view_of_another_role', 'pg_stat_statements', 'extension_member'
)`)
	assert.Equal(t, "public.extension_member,public.pg_stat_statements,public.table_of_another_role", relations)
}

func TestBackupRoleReadsTheDatabaseAfterTheRestore(t *testing.T) {
	t.Parallel()

	target := startTarget(t)
	target.exec(t, olderSchema)
	target.dump(t)
	target.exec(t, newerSchema)

	code, output := target.restore(t)
	require.Zero(t, code, output)

	backupConn := target.connect(t, backupRole)
	for _, table := range []string{"databasechangelog", "process_instance"} {
		_, err := backupConn.Exec(t.Context(), "SELECT count(*) FROM "+table)
		assert.NoError(t, err, table)
	}

	// Camunda creates new tables on its next upgrade, and the next dump reads
	// them.
	target.exec(t, "CREATE TABLE created_after_the_restore (id BIGINT)")
	_, err := backupConn.Exec(t.Context(), "SELECT count(*) FROM created_after_the_restore")
	assert.NoError(t, err)
}

func TestRetryAfterAFailedRestoreReachesTheDatabaseOfTheDump(t *testing.T) {
	t.Parallel()

	target := startTarget(t)
	target.exec(t, olderSchema)
	dumped := target.objects(t)
	target.dump(t)
	target.exec(t, newerSchema)

	// A dump cut in half fails pg_restore after it created the tables, as an
	// interrupted download or a killed pod does.
	target.shell(t, "cp /scratch/camunda.dump /scratch/full.dump && "+
		"head -c $(($(stat -c %s /scratch/full.dump) / 2)) /scratch/full.dump > /scratch/camunda.dump")
	code, _ := target.restore(t)
	require.NotZero(t, code)

	target.shell(t, "cp /scratch/full.dump /scratch/camunda.dump")
	code, output := target.restore(t)

	require.Zero(t, code, output)
	assert.Equal(t, dumped, target.objects(t))
	assert.Equal(t, "ACTIVE", target.queryString(t, "SELECT state FROM process_instance"))
}

func TestRetryAfterAFailedDropReachesTheDatabaseOfTheDump(t *testing.T) {
	t.Parallel()

	target := startTarget(t)
	target.exec(t, olderSchema)
	dumped := target.objects(t)
	target.dump(t)
	target.exec(t, newerSchema)
	before := target.objects(t)

	// The drop takes the relations in name order. A lock on process_instance
	// makes it fail after it dropped the relations before it.
	locker := target.connect(t, backupRole)
	tx, err := locker.Begin(t.Context())
	require.NoError(t, err)
	_, err = tx.Exec(t.Context(), "LOCK TABLE process_instance IN ACCESS SHARE MODE")
	require.NoError(t, err)

	code, output := target.run(t, target.jobContainer(t, "drop"), "PGOPTIONS=-c lock_timeout=1s")
	require.NotZero(t, code)
	assert.Contains(t, output, "lock timeout")
	assert.Equal(t, before, target.objects(t), "a failed drop drops nothing")

	require.NoError(t, tx.Rollback(t.Context()))
	code, output = target.restore(t)

	require.Zero(t, code, output)
	assert.Equal(t, dumped, target.objects(t))
}

// restoreTarget is one PostgreSQL server with the target database and its
// roles, and the commands of both Jobs run against it.
type restoreTarget struct {
	container *postgres.PostgresContainer
	// server reaches the server from the test as the admin role.
	server pgbootstrap.Connection
	// app is a connection to the target database as the application role.
	app *pgx.Conn
	// secrets holds the keys of the credential Secrets that the Jobs read.
	secrets map[string]map[string]string
}

// startTarget runs one PostgreSQL server for the test and sets up the target
// database and its roles with pkg/pgbootstrap.
func startTarget(t *testing.T) *restoreTarget {
	t.Helper()

	ctx, cancel := context.WithTimeout(t.Context(), 5*time.Minute)
	defer cancel()

	container, err := postgres.Run(
		ctx, postgresImage,
		postgres.WithDatabase("postgres"),
		postgres.WithUsername("postgres"),
		postgres.WithPassword("admin-secret"),
		postgres.BasicWaitStrategies(),
	)
	require.NoError(t, err)
	t.Cleanup(func() { _ = testcontainers.TerminateContainer(container) })

	host, err := container.Host(ctx)
	require.NoError(t, err)
	port, err := container.MappedPort(ctx, "5432/tcp")
	require.NoError(t, err)
	admin := pgbootstrap.Connection{
		Host:     host,
		Port:     int32(port.Num()),
		User:     "postgres",
		Password: "admin-secret",
		SSLMode:  "disable",
	}

	bootstrap, err := pgbootstrap.Connect(ctx, admin)
	require.NoError(t, err)
	defer bootstrap.Close()
	require.NoError(t, bootstrap.EnsureDatabase(ctx, targetDatabase))
	require.NoError(t, bootstrap.EnsureUser(ctx, applicationRole, rolePassword))
	require.NoError(t, bootstrap.GrantApplication(ctx, applicationRole, targetDatabase))
	require.NoError(t, bootstrap.EnsureBackupUser(ctx, backupRole, rolePassword, targetDatabase))

	// The Jobs write and read the dump under the mount path of the scratch
	// volume.
	code, _, err := container.Exec(ctx, []string{"mkdir", "-p", scratchMountPath})
	require.NoError(t, err)
	require.Zero(t, code)

	target := &restoreTarget{
		container: container,
		server:    admin,
		secrets: map[string]map[string]string{
			applicationSecret: {"username": applicationRole, "password": rolePassword},
			backupSecret:      {"username": backupRole, "password": rolePassword},
		},
	}
	target.app = target.connect(t, applicationRole)

	return target
}

// exec runs sql in the target database as the application role, as Camunda's
// schema migration does.
func (r *restoreTarget) exec(t *testing.T, sql string) {
	t.Helper()

	_, err := r.app.Exec(t.Context(), sql)
	require.NoError(t, err)
}

// dump runs the dump container of the dump Job and requires it to succeed.
func (r *restoreTarget) dump(t *testing.T) {
	t.Helper()

	job, err := backup.BuildJob(backup.JobInput{
		Backup: &v1.LogicalBackupRDBMS{
			ObjectMeta: metav1.ObjectMeta{Name: "my-cluster-backup", Namespace: "my-cluster-ns", UID: "backup-uid"},
		},
		ClusterName:   "my-cluster",
		Bucket:        s3Bucket(s3Credentials()),
		DBSecretName:  backupSecret,
		DBUsernameKey: "username",
		DBPasswordKey: "password",
		ServerVersion: "17",
		Host:          "127.0.0.1",
		Port:          5432,
		Database:      targetDatabase,
		CLIImage:      "ghcr.io/konsole-is/camunda-operator-cli:0.1.0",
	})
	require.NoError(t, err)

	code, output := r.run(t, job.Spec.Template.Spec.InitContainers[0])
	require.Zero(t, code, output)
}

// connect opens a connection to the target database as role. Test cleanup
// closes it.
func (r *restoreTarget) connect(t *testing.T, role string) *pgx.Conn {
	t.Helper()

	c := r.server
	c.User = role
	c.Password = rolePassword
	conn, err := pgbootstrap.Open(t.Context(), c, targetDatabase)
	require.NoError(t, err)
	t.Cleanup(func() { _ = conn.Close(context.Background()) })

	return conn
}

// restore runs the drop container and the restore container of the restore
// Job, as one pod of the Job does. It returns the exit code and the output of
// the first container that fails, or zero.
func (r *restoreTarget) restore(t *testing.T) (int, string) {
	t.Helper()

	for _, name := range []string{"drop", "restore"} {
		if code, output := r.run(t, r.jobContainer(t, name)); code != 0 {
			return code, output
		}
	}

	return 0, ""
}

// jobContainer returns the container of the restore Job with the given name.
func (r *restoreTarget) jobContainer(t *testing.T, name string) corev1.Container {
	t.Helper()

	in := input()
	in.DBSecretName = applicationSecret
	in.Host = "127.0.0.1"
	in.Database = targetDatabase
	job, err := BuildJob(in)
	require.NoError(t, err)

	containers := append(slices.Clone(job.Spec.Template.Spec.InitContainers), job.Spec.Template.Spec.Containers...)
	i := slices.IndexFunc(containers, func(c corev1.Container) bool { return c.Name == name })
	require.GreaterOrEqual(t, i, 0, name)

	return containers[i]
}

// shell runs script with sh inside the PostgreSQL container and requires it
// to succeed.
func (r *restoreTarget) shell(t *testing.T, script string) {
	t.Helper()

	code, output := r.run(t, corev1.Container{Command: []string{"sh", "-c", script}})
	require.Zero(t, code, output)
}

// run executes the command of container inside the PostgreSQL container, with
// the environment of container, its Secret references resolved, and extra
// variables after it.
func (r *restoreTarget) run(t *testing.T, container corev1.Container, extra ...string) (int, string) {
	t.Helper()

	env := make([]string, 0, len(container.Env)+len(extra))
	for _, e := range container.Env {
		value := e.Value
		if e.ValueFrom != nil {
			ref := e.ValueFrom.SecretKeyRef
			value = r.secrets[ref.Name][ref.Key]
		}
		env = append(env, e.Name+"="+value)
	}
	env = append(env, extra...)

	// Kubernetes turns $$ in a container command into $.
	command := make([]string, 0, len(container.Command))
	for _, arg := range container.Command {
		command = append(command, strings.ReplaceAll(arg, "$$", "$"))
	}

	code, reader, err := r.container.Exec(
		t.Context(), command, tcexec.Multiplexed(), tcexec.WithEnv(env),
	)
	require.NoError(t, err)
	output, err := io.ReadAll(reader)
	require.NoError(t, err)

	return code, string(output)
}

// objects lists the tables, columns, indexes, sequences, and views of the
// public schema, sorted.
func (r *restoreTarget) objects(t *testing.T) []string {
	t.Helper()

	rows, err := r.app.Query(t.Context(), `
SELECT object FROM (
	SELECT 'table ' || tablename FROM pg_tables WHERE schemaname = 'public'
	UNION ALL
	SELECT 'column ' || table_name || '.' || column_name FROM information_schema.columns WHERE table_schema = 'public'
	UNION ALL
	SELECT 'index ' || indexname FROM pg_indexes WHERE schemaname = 'public'
	UNION ALL
	SELECT 'sequence ' || sequencename FROM pg_sequences WHERE schemaname = 'public'
	UNION ALL
	SELECT 'view ' || viewname FROM pg_views WHERE schemaname = 'public'
	UNION ALL
	SELECT 'materialized view ' || matviewname FROM pg_matviews WHERE schemaname = 'public'
) AS objects (object)
ORDER BY object COLLATE "C"`)
	require.NoError(t, err)
	objects, err := pgx.CollectRows(rows, pgx.RowTo[string])
	require.NoError(t, err)

	return objects
}

// changesets lists the ids of the changelog rows in the order they ran.
func (r *restoreTarget) changesets(t *testing.T) []string {
	t.Helper()

	rows, err := r.app.Query(t.Context(), "SELECT id FROM databasechangelog ORDER BY orderexecuted")
	require.NoError(t, err)
	ids, err := pgx.CollectRows(rows, pgx.RowTo[string])
	require.NoError(t, err)

	return ids
}

// queryString runs a query that returns one text value.
func (r *restoreTarget) queryString(t *testing.T, sql string) string {
	t.Helper()

	var value string
	require.NoError(t, r.app.QueryRow(t.Context(), sql).Scan(&value))

	return value
}
